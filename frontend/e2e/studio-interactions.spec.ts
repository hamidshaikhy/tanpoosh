import { test, expect } from "@playwright/test";

test("select first, explicitly display, preserve size, retry photo errors and download", async ({ page }) => {
  const errors: string[] = [], heavy: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (/\.(glb|gltf|fbx)(\?|$)/i.test(r.url())) heavy.push(r.url()); });
  await page.setViewportSize({ width: 1918, height: 919 });
  await page.goto("/studio");
  const wardrobe = page.getByTestId("wardrobe-panel"), photo = page.getByTestId("model-photo");
  await expect(page.getByTestId("show-look")).toBeDisabled();
  await expect(photo).toHaveAttribute("data-preview-key", "reference");
  const shirt = wardrobe.locator('[data-product="oxford-shirt"]');
  await shirt.getByRole("button", { name: "سفید، پیراهن آکسفورد", exact: true }).click();
  const size = page.locator('select[id^="size-top-"]:visible');
  await size.selectOption("M");
  await wardrobe.getByRole("tab", { name: "شلوار", exact: true }).click();
  await wardrobe.locator('[data-product="tailored-trousers"]').getByTestId("wardrobe-item").click();
  await wardrobe.getByRole("tab", { name: "کفش", exact: true }).click();
  await wardrobe.locator('[data-product="derby-shoes"]').getByTestId("wardrobe-item").click();
  await expect(photo.getByTestId("outfit-photo-layer")).toHaveCount(0);
  await page.getByTestId("show-look").click();
  await expect(photo).toHaveAttribute("data-preview-key", /top:oxford-shirt:white/);
  await expect(photo.getByTestId("outfit-photo-layer")).toHaveCount(3);
  const resultKey = await photo.getAttribute("data-preview-key");
  await size.selectOption("L");
  await expect(photo).toHaveAttribute("data-preview-key", resultKey!);
  await wardrobe.getByRole("tab", { name: "بالاپوش", exact: true }).click();
  await shirt.getByRole("button", { name: "آبی آسمانی، پیراهن آکسفورد", exact: true }).click();
  await expect(size).toHaveValue("L");
  await expect(photo).toHaveAttribute("data-preview-key", resultKey!);
  await expect(page.getByText(/انتخابت تغییر کرده/)).toBeVisible();
  await page.route("**/studio-images/oxford-shirt/sky-layer.webp", route => route.abort());
  await page.getByTestId("show-look").click();
  await expect(page.getByRole("alert").filter({ hasText: "عکس استایل بارگذاری نشد" })).toBeVisible();
  await expect(photo).toHaveAttribute("data-preview-key", resultKey!);
  await page.unroute("**/studio-images/oxford-shirt/sky-layer.webp");
  await page.getByTestId("show-look").click();
  await expect(photo).toHaveAttribute("data-preview-key", /top:oxford-shirt:sky/);
  const skyKey = await photo.getAttribute("data-preview-key");
  await page.getByRole("button", { name: "واگرد", exact: true }).click();
  await expect(page.getByText(/انتخابت تغییر کرده/)).toBeVisible();
  await page.getByRole("button", { name: "ازنو", exact: true }).click();
  await expect(photo).toHaveAttribute("data-preview-key", skyKey!);
  await expect(page.getByText(/انتخابت تغییر کرده/)).toBeHidden();
  const downloadEvent = page.waitForEvent("download");
  await page.getByTestId("download-look").click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe("tanpoosh-my-look.jpg");
  await download.saveAs("../.local-tools/screenshots/look-download.jpg");
  await page.getByRole("button", { name: "بزرگ‌نمایی عکس استایل", exact: true }).click();
  const expanded = page.getByRole("dialog", { name: "استایل انتخابی روی مدل", exact: true });
  await expect(expanded).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(expanded).toBeHidden();
  for (const viewport of [{ width: 1024, height: 1200 }, { width: 1918, height: 919 }, { width: 1280, height: 720 }]) {
    await page.setViewportSize(viewport);
    expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    const bounds = (await photo.boundingBox())!;
    expect(bounds.width / bounds.height).toBeCloseTo(2 / 3, 2);
    await page.mouse.move(viewport.width / 2, 300);
    await page.mouse.wheel(0, 600);
    expect(await page.evaluate(() => scrollY)).toBe(0);
  }
  await page.screenshot({ path: "../.local-tools/screenshots/studio-photo-desktop.png" });
  await expect(page.locator("canvas")).toHaveCount(0);
  await page.getByRole("button", { name: "بازنشانی استایل", exact: true }).click();
  await expect(photo).toHaveAttribute("data-preview-key", "reference");
  await expect(photo.getByTestId("outfit-photo-layer")).toHaveCount(0);
  await expect(page.getByTestId("show-look")).toBeDisabled();
  expect(heavy).toEqual([]);
  expect(errors).toEqual([]);
});

test("newest navigation is underlined and collection products open their details", async ({ page }) => {
  await page.goto("/");
  const nav = page.getByRole("navigation", { name: "پیمایش اصلی" });
  const newest = nav.getByRole("link", { name: "جدیدترین‌ها", exact: true });
  const clothing = nav.getByRole("link", { name: "پوشاک", exact: true });
  await newest.click();
  await expect(page).toHaveURL(/is_new=1/);
  await expect(newest).toHaveAttribute("aria-current", "page");
  await expect(newest).toHaveCSS("text-decoration-line", "underline");
  await expect(clothing).not.toHaveAttribute("aria-current", "page");
  await clothing.click();
  await expect(clothing).toHaveAttribute("aria-current", "page");
  await expect(newest).not.toHaveAttribute("aria-current", "page");
  await page.goto("/collections/old-money");
  const product = page.locator('main a[href^="/products/"]').first();
  const href = await product.getAttribute("href");
  await product.click();
  await expect(page).toHaveURL(new RegExp(href!));
  await expect(page.locator("h1")).toBeVisible();
});
