import { test, expect } from "@playwright/test";

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
test("mobile photo studio stays inside viewport and opens its outfit sheet", async ({ page, context }) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("/studio");
  await expect(page.getByTestId("show-look")).toBeDisabled();
  await page.getByRole("button", { name: "کلاسیک با عینک", exact: true }).click();
  await page.getByTestId("show-look").click();
  await expect(page.getByTestId("model-photo")).not.toHaveAttribute("data-preview-key", "reference");
  await expect(page.getByTestId("model-photo").getByTestId("outfit-photo-layer")).toHaveCount(4);
  const downloadEvent = page.waitForEvent("download");
  await page.getByTestId("download-look").click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe("tanpoosh-my-look.jpg");
  await download.saveAs("../.local-tools/screenshots/look-eyewear-download.jpg");
  await expect(page.locator("canvas")).toHaveCount(0);
  const stage = (await page.getByTestId("photo-stage").boundingBox())!;
  const x = stage.x + stage.width / 2, y = stage.y + stage.height / 2;
  const session = await context.newCDPSession(page);
  await session.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y }] });
  await session.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x, y: y - 80 }] });
  await session.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
  expect(await page.evaluate(() => scrollY)).toBe(0);
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true);
  await page.screenshot({ path: "../.local-tools/screenshots/studio-photo-mobile.png" });
  await page.getByRole("button", { name: "بزرگ‌نمایی عکس استایل", exact: true }).click();
  const enlarged = page.getByTestId("expanded-photo");
  const bounds = (await enlarged.boundingBox())!;
  expect(bounds.width / bounds.height).toBeCloseTo(2 / 3, 2);
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(390);
  await page.getByRole("dialog", { name: "استایل انتخابی روی مدل", exact: true }).getByRole("button", { name: "بستن", exact: true }).click();
  await page.getByRole("button", { name: "مشاهدهٔ استایل", exact: true }).click();
  const sheet = page.getByRole("dialog", { name: "استایل شما" });
  await expect(sheet).toBeVisible();
  await expect(sheet.locator("select")).toHaveCount(4);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});
