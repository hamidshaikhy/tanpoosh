"""Create backend/.env for LOCAL DEVELOPMENT with freshly generated secrets.

Usage:  python scripts/init_local_env.py [--postgres-password-file PATH] [--force]

Never use the generated file in production; production settings refuse insecure values.
The file is git-ignored.
"""

from __future__ import annotations

import argparse
import base64
import contextlib
import os
import secrets
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--postgres-password-file", default=str(ROOT.parent / ".local-tools" / "pg-app-password.txt"))
    parser.add_argument("--postgres-password", default=None)
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--public-url", default="http://localhost:8088")
    args = parser.parse_args()

    target = ROOT / ".env"
    if target.exists() and not args.force:
        print(f"{target} already exists (use --force to regenerate).")
        return

    pg_password = args.postgres_password
    if pg_password is None:
        pw_file = Path(args.postgres_password_file)
        pg_password = pw_file.read_text(encoding="utf-8").strip() if pw_file.exists() else "CHANGE_ME"

    fernet_key = base64.urlsafe_b64encode(os.urandom(32)).decode()
    lines = [
        "# Generated by scripts/init_local_env.py — LOCAL DEVELOPMENT ONLY. Do not commit.",
        "DJANGO_ENV=development",
        "DJANGO_SETTINGS_MODULE=config.settings.development",
        f"DJANGO_SECRET_KEY={secrets.token_urlsafe(64)}",
        "DJANGO_DEBUG=true",
        "DJANGO_ALLOWED_HOSTS=localhost,127.0.0.1",
        f"PUBLIC_BASE_URL={args.public_url}",
        f"CSRF_TRUSTED_ORIGINS={args.public_url}",
        "TRUSTED_PROXY_COUNT=1",
        "FRONTEND_INTERNAL_URL=http://127.0.0.1:3000",
        f"FRONTEND_REVALIDATE_SECRET={secrets.token_urlsafe(32)}",
        "POSTGRES_DB=tanpoosh",
        "POSTGRES_USER=tanpoosh",
        f"POSTGRES_PASSWORD={pg_password}",
        "POSTGRES_HOST=127.0.0.1",
        "POSTGRES_PORT=5432",
        "REDIS_URL=redis://127.0.0.1:6379/0",
        "CACHE_REDIS_URL=redis://127.0.0.1:6379/1",
        "RATELIMIT_REDIS_URL=redis://127.0.0.1:6379/2",
        "EMAIL_HOST=127.0.0.1",
        "EMAIL_PORT=2525",
        f"MFA_ENCRYPTION_KEY={fernet_key}",
        "MFA_DEV_BYPASS=true",
        "PAYMENT_PROVIDER=mock",
        "ZARINPAL_MODE=sandbox",
        "# Sandbox accepts any UUID-format merchant id; a live merchant id is an external prerequisite.",
        f"ZARINPAL_MERCHANT_ID={uuid.uuid4()}",
        "PAYMENT_MOCK_ENABLED=true",
        "OWNER_USERNAME=tanpoosh_admin",
    ]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    with contextlib.suppress(OSError):
        os.chmod(target, 0o600)
    print(f"Wrote {target}")
    print("Also share FRONTEND_REVALIDATE_SECRET with frontend/.env.local (scripts/sync_frontend_env.py does this).")


if __name__ == "__main__":
    main()
