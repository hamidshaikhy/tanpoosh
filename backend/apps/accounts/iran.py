_PERSIAN_PLACE = re.compile(r"^[؀-ۿ‌ ]{2,40}$")


def is_valid_province(value: str) -> bool:
    return normalize_text(value) in PROVINCES


def is_valid_city(province: str, city: str) -> bool:
    province = normalize_text(province)
    city = normalize_text(city)
    if province not in PROVINCES:
        return False
    return city in PROVINCES[province] or bool(_PERSIAN_PLACE.match(city))


def as_list() -> list[dict[str, object]]:
    return [{"name": name, "cities": cities} for name, cities in PROVINCES.items()]
